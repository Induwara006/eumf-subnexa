"""Format finished subtitles without changing translation/cache contents.

SRT does not consistently support colors in video players. ASS supports a styled
red/white credit in compatible players; SRT uses a plain-text fallback.
"""
from datetime import timedelta
import os
import re
import srt

CREDIT_TEXT = 'Sinhala Sub Generated by SubNexa AI'
CREDIT_REQUIRED_GAP = timedelta(seconds=5)
CREDIT_END = timedelta(milliseconds=4500)


def _with_credit(subtitles, enabled):
    items = list(subtitles)
    if not items:
        raise ValueError('There are no subtitles to export.')
    first_start = min(sub.start for sub in items)
    added = bool(enabled and first_start >= CREDIT_REQUIRED_GAP)
    if not added:
        return items, False
    credit = srt.Subtitle(index=0, start=timedelta(0), end=CREDIT_END,
                          content=CREDIT_TEXT)
    return [credit, *items], True


def _ass_time(value):
    # ASS centiseconds, always round down to avoid moving past an SRT boundary.
    total = max(0, int(value.total_seconds() * 100))
    hours, rest = divmod(total, 360000)
    mins, rest = divmod(rest, 6000)
    secs, cs = divmod(rest, 100)
    return f'{hours}:{mins:02d}:{secs:02d}.{cs:02d}'


def _ass_text(value):
    # Do not allow user subtitle text to inject ASS override/style tags.
    return (value.replace('\\', '＼')
                 .replace('{', '｛').replace('}', '｝')
                 .replace('\r\n', '\n').replace('\r', '\n')
                 .replace('\n', r'\N'))


def _ass(subtitles, credit_added):
    header = '''[Script Info]
Title: EUMF SubNexa Sinhala Subtitles
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
PlayResX: 1920
PlayResY: 1080

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Nirmala UI,48,&H00FFFFFF,&H00FFFFFF,&H00000000,&H64000000,0,0,0,0,100,100,0,0,1,2,1,2,55,55,42,1
Style: SubNexaCredit,Nirmala UI,46,&H00FFFFFF,&H00FFFFFF,&H00000000,&H64000000,-1,0,0,0,100,100,0,0,1,2,0,5,55,55,42,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
'''
    rows = []
    for sub in sorted(subtitles, key=lambda x: (x.start, x.end)):
        is_credit = credit_added and sub.index == 0 and sub.content == CREDIT_TEXT
        style = 'SubNexaCredit' if is_credit else 'Default'
        if is_credit:
            # ASS uses BGR color: #E50914 -> &H1409E5&.
            text = r'{\an5\c&HFFFFFF&}Sinhala Sub {\c&H1409E5&}Generated by SubNexa AI'
        else:
            text = _ass_text(sub.content)
        rows.append(f'Dialogue: 0,{_ass_time(sub.start)},{_ass_time(sub.end)},'
                    f'{style},,0,0,0,,{text}')
    return header + '\n'.join(rows) + '\n'


def render_subtitles(subtitles, output_format='srt', opening_credit=False):
    """Return (contents, credit_added); SRT always preserves every original timestamp.

    If a credit is added the original indices shift by one for valid SRT ordering.
    """
    if output_format not in ('srt', 'ass'):
        raise ValueError('Output format must be srt or ass.')
    entries, credit_added = _with_credit(subtitles, opening_credit)
    if output_format == 'srt':
        return srt.compose(entries, reindex=True), credit_added
    return _ass(entries, credit_added), credit_added


def download_filename(uploaded_filename, output_format):
    """Preserve user file stem; prevent unsafe path/control characters in headers."""
    if output_format not in ('srt', 'ass'):
        raise ValueError('Output format must be srt or ass.')
    basename = os.path.basename(str(uploaded_filename or '').replace('\\', '/'))
    stem = re.sub(r'\.srt$', '', basename, flags=re.IGNORECASE)
    # Keep original language/scripts and spaces; only remove invalid filename chars.
    stem = re.sub(r'[<>:"/\\|?*\x00-\x1f]', '_', stem).strip(' .') or 'subtitles'
    return f'{stem}_generated_by_subnexa_ai.{output_format}'
